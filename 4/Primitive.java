public class Primitive {
    public static void main(String[] args) {

        // 変数の宣言と初期化
        byte a = 100;
        short b = 1000;
        int c = 100_000_000;
        long d = 1_000_000_000_000L;

        // 変数の値を出力
        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
        System.out.println(d);
    }    
}
