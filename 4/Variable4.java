public class Variable4 {
    public static void main(String[] args) {
        
        // 変数の宣言と初期化；
        var a = 123;
        var b = 4.56;
        var c = 'A';
        var d = "Hello";

        // 変数の値を出力
        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
        System.out.println(d);
    }    
}
